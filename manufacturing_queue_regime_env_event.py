"""
Event-triggered strongly heterogeneous four-station manufacturing environment.

Revision goals
--------------
1. A policy decision is requested only when one or more stations can load a job.
2. The action is factorized as four station-wise categorical actions:
      0 = decrease, 1 = maintain, 2 = increase.
3. Inactive stations are forced to maintain and are excluded from actor loss.
4. One policy transition may span multiple primitive simulation ticks.
5. Feasible stock-removal actions are enforced through a [4, 3] action mask.
6. The observation contains only the state variables listed in the case-study
   document: G_i, T_i, b_i, c_i, D_M, Y, q, tau_i, o_i, and time to arrival.
7. Heterogeneity is generated by a latent semi-Markov operating regime that
   creates distinct station-allocation, throughput, and quality trade-offs.
8. The primitive reward has five one-to-one components:
      yield - Type-I defects - Type-II defects - buffer-WIP change - lost orders.
9. Downtime and auxiliary reward shaping are intentionally excluded so that the
   benchmark remains interpretable while preserving strong regime heterogeneity.

The active-station mask and regime label are returned through ``info`` rather
than appended to the state vector. The regime label is intended for critic/gate
supervision during training and for diagnostics; the learned gate receives only
state features.
"""
from __future__ import annotations

from dataclasses import dataclass
from typing import Dict, List, Optional, Sequence, Tuple

import numpy as np


class SimpleBox:
    def __init__(self, shape: Tuple[int, ...], dtype=np.float32):
        self.shape = shape
        self.dtype = dtype


class SimpleMultiDiscrete:
    def __init__(self, nvec: Sequence[int]):
        self.nvec = np.asarray(nvec, dtype=np.int64)
        self.shape = self.nvec.shape


@dataclass
class Job:
    total_stock_removed: float = 0.0
    arrival_time: float = 0.0
    operation_completed: bool = False
    assigned_commanded_removal: float = 0.0
    assigned_actual_removal: float = 0.0
    assigned_cycle_time: float = 0.0
    assigned_type1_probability: float = 0.0

    def prepare_operation(
        self,
        commanded_removal: float,
        actual_removal: float,
        cycle_time: float,
        type1_probability: float,
    ) -> None:
        self.operation_completed = False
        self.assigned_commanded_removal = float(commanded_removal)
        self.assigned_actual_removal = float(actual_removal)
        self.assigned_cycle_time = float(cycle_time)
        self.assigned_type1_probability = float(type1_probability)

    def clear_operation_snapshot(self) -> None:
        self.operation_completed = False
        self.assigned_commanded_removal = 0.0
        self.assigned_actual_removal = 0.0
        self.assigned_cycle_time = 0.0
        self.assigned_type1_probability = 0.0

    def finish_operation(self) -> None:
        self.operation_completed = True


class ManufacturingQueueRegimeEventEnv:
    """Four-station serial manufacturing line with event-triggered control."""

    REGIME_NAMES = ["normal", "congestion", "starvation", "quality_risk"]
    NORMAL = 0
    CONGESTION = 1
    STARVATION = 2
    QUALITY_RISK = 3

    ACTION_DELTAS = np.array([-1, 0, 1], dtype=np.int64)
    DECREASE = 0
    MAINTAIN = 1
    INCREASE = 2

    def __init__(
        self,
        num_stations: int = 4,
        episode_horizon: int = 300,
        dt: float = 1.0,
        seed: Optional[int] = None,
        arrival_distribution: str = "exponential",
        base_arrival_rate: float = 0.27,
        max_input_queue: int = 50,
        phi: float = 0.05,
        # Five-component reward: dY - dD_I - dD_II - db - dL.
        yield_reward: float = 1.0,
        type1_penalty: float = 1.0,
        type2_penalty: float = 1.0,
        buffer_change_penalty: float = 1.0,
        lost_order_penalty: float = 1.0,
        # Type-I defect-risk parameters.
        type1_alpha: float = 0.32,
        type1_probability_max: float = 0.80,
        # Feasible process envelope. Enforced by action masking.
        stock_ratio_min: float = 0.65,
        stock_ratio_max: float = 1.35,
        # Initial setting is deliberately under-removing.
        initial_stock_ratios: Sequence[float] = (0.84, 0.88, 0.92, 0.96),
        # Process-time stochasticity.
        process_time_cv: float = 0.08,
        # Latent semi-Markov regime process.
        min_regime_duration: int = 70,
        max_regime_duration: int = 120,
        random_initial_regime: bool = True,
        fixed_regime: Optional[int] = None,
    ) -> None:
        self.M = int(num_stations)
        if self.M != 4:
            raise ValueError("This benchmark requires num_stations=4.")
        if episode_horizon < 1:
            raise ValueError("episode_horizon must be positive.")
        if dt <= 0.0:
            raise ValueError("dt must be positive.")
        if not 0.0 < phi < 1.0:
            raise ValueError("phi must satisfy 0 < phi < 1.")
        if base_arrival_rate <= 0.0:
            raise ValueError("base_arrival_rate must be positive.")
        if not 0.0 < stock_ratio_min < 1.0 < stock_ratio_max:
            raise ValueError("Require 0 < stock_ratio_min < 1 < stock_ratio_max.")
        if min_regime_duration < 1 or max_regime_duration < min_regime_duration:
            raise ValueError("Invalid regime-duration bounds.")
        if fixed_regime is not None and int(fixed_regime) not in range(4):
            raise ValueError("fixed_regime must be one of 0, 1, 2, 3, or None.")

        self.episode_horizon = int(episode_horizon)
        self.dt = float(dt)
        self.horizon_time = self.episode_horizon * self.dt
        self.arrival_distribution = str(arrival_distribution)
        self.base_arrival_rate = float(base_arrival_rate)
        self.max_input_queue = int(max_input_queue)
        self.phi = float(phi)

        self.yield_reward = float(yield_reward)
        self.type1_penalty = float(type1_penalty)
        self.type2_penalty = float(type2_penalty)
        self.buffer_change_penalty = float(buffer_change_penalty)
        self.lost_order_penalty = float(lost_order_penalty)
        self.type1_alpha = float(type1_alpha)
        self.type1_probability_max = float(type1_probability_max)

        self.stock_ratio_min = float(stock_ratio_min)
        self.stock_ratio_max = float(stock_ratio_max)
        self.initial_stock_ratios = np.asarray(initial_stock_ratios, dtype=np.float32)
        if self.initial_stock_ratios.shape != (self.M,):
            raise ValueError("initial_stock_ratios must contain four values.")
        if np.any(self.initial_stock_ratios < self.stock_ratio_min) or np.any(
            self.initial_stock_ratios > self.stock_ratio_max
        ):
            raise ValueError("Initial stock ratios must lie inside the feasible bounds.")

        self.process_time_cv = float(process_time_cv)
        self.min_regime_duration = int(min_regime_duration)
        self.max_regime_duration = int(max_regime_duration)
        self.random_initial_regime = bool(random_initial_regime)
        self.fixed_regime = None if fixed_regime is None else int(fixed_regime)

        # Desired station-wise removal contributions. Their sum is 3.10.
        self.stock_target = np.array([1.50, 0.90, 0.45, 0.25], dtype=np.float32)
        self.base_cycle_time = np.array([4.5, 4.0, 3.5, 3.0], dtype=np.float32)
        self.buffer_capacity = np.array([12, 24, 16], dtype=np.int32)
        self.target_total_stock = float(np.sum(self.stock_target))
        self.dim_tolerance = 0.08 * self.target_total_stock
        self.stock_min = self.stock_ratio_min * self.stock_target
        self.stock_max = self.stock_ratio_max * self.stock_target

        # Strong heterogeneous regime profiles are specified directly.  The
        # previous baseline/strong interpolation and downtime-specific arrays
        # are removed to keep the benchmark compact and interpretable.
        self.regime_transition = np.array(
            [
                [0.05, 0.35, 0.30, 0.30],
                [0.30, 0.05, 0.30, 0.35],
                [0.30, 0.35, 0.05, 0.30],
                [0.35, 0.30, 0.30, 0.05],
            ],
            dtype=np.float64,
        )

        self.arrival_rate_multiplier = np.array(
            [1.00, 2.00, 0.35, 1.00], dtype=np.float64
        )
        self.station_process_multipliers = np.array(
            [
                [1.00, 1.00, 1.00, 1.00],
                [0.90, 1.00, 1.40, 1.65],
                [1.40, 1.20, 0.90, 0.80],
                [1.03, 1.10, 1.22, 1.35],
            ],
            dtype=np.float32,
        )
        self.actual_removal_bias = np.array(
            [
                [0.00, 0.00, 0.00, 0.00],
                [0.05, 0.03, -0.07, -0.10],
                [-0.08, -0.04, 0.05, 0.08],
                [-0.09, -0.05, 0.04, 0.08],
            ],
            dtype=np.float32,
        )
        self.actual_removal_cv = np.array(
            [
                [0.010, 0.010, 0.010, 0.010],
                [0.012, 0.014, 0.022, 0.026],
                [0.020, 0.017, 0.012, 0.010],
                [0.035, 0.030, 0.020, 0.015],
            ],
            dtype=np.float32,
        )
        self.quality_multiplier = np.array(
            [
                [1.00, 1.00, 1.00, 1.00],
                [0.85, 1.00, 1.60, 2.00],
                [1.90, 1.45, 0.90, 0.80],
                [3.00, 2.40, 1.60, 1.30],
            ],
            dtype=np.float32,
        )
        self.safe_removal_ratio = np.array(
            [
                [0.98, 0.98, 0.98, 0.98],
                [1.10, 1.02, 0.88, 0.82],
                [0.82, 0.88, 1.06, 1.10],
                [0.78, 0.84, 0.98, 1.04],
            ],
            dtype=np.float32,
        )
        self.dimensional_noise_cv = np.array(
            [0.008, 0.011, 0.013, 0.025], dtype=np.float32
        )

        self.action_space = SimpleMultiDiscrete([3] * self.M)

        # State exactly follows the case-study document:
        # G(4), T(4), b(3), c(4), DM(1), Y(1), q(1), tau(4), o(4), eta(1).
        self.state_slices = {
            "G": slice(0, 4),
            "T": slice(4, 8),
            "b": slice(8, 11),
            "c": slice(11, 15),
            "DM": slice(15, 16),
            "Y": slice(16, 17),
            "q": slice(17, 18),
            "tau": slice(18, 22),
            "o": slice(22, 26),
            "eta": slice(26, 27),
        }
        self.observation_space = SimpleBox((27,), dtype=np.float32)

        self.rng = np.random.default_rng(seed)
        self.reset(seed=seed)

    # ------------------------------------------------------------------
    # Latent regime process
    # ------------------------------------------------------------------
    def _sample_regime_duration(self) -> int:
        return int(self.rng.integers(self.min_regime_duration, self.max_regime_duration + 1))

    def _set_regime(self, regime_id: int, resample_arrival_clock: bool) -> None:
        self.latent_regime = int(regime_id)
        self.regime_time_remaining = (
            self.episode_horizon + 1
            if self.fixed_regime is not None
            else self._sample_regime_duration()
        )
        self.current_arrival_rate = float(
            self.base_arrival_rate
            * self.arrival_rate_multiplier[self.latent_regime]
        )
        # T_i is the expected cycle-time setpoint under the current regime,
        # whereas remaining_time stores the noisy realized processing time.
        if hasattr(self, "G"):
            self.T = np.asarray(
                [
                    self._expected_cycle_time_from_G(i, float(self.G[i]))
                    for i in range(self.M)
                ],
                dtype=np.float32,
            )
        if resample_arrival_clock:
            self.next_arrival_time = (
                self.time + self._sample_interarrival_time()
            )

    def _advance_regime_clock(self) -> None:
        if self.fixed_regime is not None:
            return
        self.regime_time_remaining -= 1
        if self.regime_time_remaining > 0:
            return
        probs = self.regime_transition[self.latent_regime]
        next_regime = int(self.rng.choice(self.M, p=probs))
        self._set_regime(next_regime, resample_arrival_clock=True)

    @property
    def regime_id(self) -> int:
        return int(self.latent_regime)

    @property
    def regime_name(self) -> str:
        return self.REGIME_NAMES[self.regime_id]

    # ------------------------------------------------------------------
    # Arrival, process, and quality models
    # ------------------------------------------------------------------
    def _sample_interarrival_time(self) -> float:
        rate = max(self.current_arrival_rate, 1e-8)
        if self.arrival_distribution == "exponential":
            return float(self.rng.exponential(1.0 / rate))
        if self.arrival_distribution == "erlang":
            shape = 2.0
            return float(self.rng.gamma(shape=shape, scale=(1.0 / rate) / shape))
        if self.arrival_distribution == "deterministic":
            return float(1.0 / rate)
        raise ValueError(f"Unknown arrival_distribution={self.arrival_distribution}")

    def _generate_arrivals_until(self, end_time: float) -> int:
        arrivals = 0
        while self.next_arrival_time <= end_time + 1e-12:
            if self.input_queue < self.max_input_queue:
                self.input_queue += 1
                arrivals += 1
            else:
                self.lost_orders += 1
            self.next_arrival_time += self._sample_interarrival_time()
        return arrivals

    def _action_factor(self, action_delta: int) -> float:
        if action_delta > 0:
            return 1.0 + self.phi
        if action_delta < 0:
            return 1.0 / (1.0 + self.phi)
        return 1.0

    def _proposed_station_G(self, station: int, action_delta: int) -> float:
        return float(self.G[station]) * self._action_factor(action_delta)

    def _expected_cycle_time_from_G(
        self, station: int, g_value: float
    ) -> float:
        # A direct proportional relation avoids an additional unsupported
        # regime/station elasticity matrix. Strong heterogeneity remains in the
        # regime-specific station process multipliers.
        removal_ratio = max(
            g_value / float(self.stock_target[station]), 1e-8
        )
        nominal = (
            float(self.base_cycle_time[station])
            * removal_ratio
            * float(self.station_process_multipliers[self.regime_id, station])
        )
        return float(np.clip(nominal, 0.5, 30.0))

    def _cycle_time_from_G(self, station: int, g_value: float) -> float:
        nominal = self._expected_cycle_time_from_G(station, g_value)
        if self.process_time_cv > 0.0:
            sigma = np.sqrt(np.log1p(self.process_time_cv**2))
            noise = float(
                self.rng.lognormal(
                    mean=-0.5 * sigma**2, sigma=sigma
                )
            )
        else:
            noise = 1.0
        return float(np.clip(nominal * noise, 0.5, 30.0))

    def _actual_removal_from_command(
        self, station: int, g_value: float
    ) -> float:
        rid = self.regime_id
        mean = g_value * (
            1.0 + float(self.actual_removal_bias[rid, station])
        )
        sd = abs(g_value) * float(
            self.actual_removal_cv[rid, station]
        )
        return float(max(0.0, self.rng.normal(mean, sd)))

    def _type1_probability_from_G(
        self, station: int, g_value: float
    ) -> float:
        rid = self.regime_id
        ratio = float(g_value / self.stock_target[station])
        safe_ratio = float(self.safe_removal_ratio[rid, station])
        overload = max(0.0, ratio - safe_ratio)
        probability = (
            self.type1_alpha
            * overload**2
            * float(self.quality_multiplier[rid, station])
        )
        return float(
            np.clip(probability, 0.0, self.type1_probability_max)
        )

    def _is_type2_defect(self, total_stock_removed: float) -> bool:
        noise_cv = float(self.dimensional_noise_cv[self.regime_id])
        measurement_noise = float(
            self.rng.normal(
                0.0, noise_cv * self.target_total_stock
            )
        )
        measured = total_stock_removed + measurement_noise
        return (
            abs(measured - self.target_total_stock)
            > self.dim_tolerance
        )

    # ------------------------------------------------------------------
    # Decision event and feasibility masks
    # ------------------------------------------------------------------
    def _update_buffer_levels(self) -> None:
        self.buffer_levels = np.asarray(
            [len(buffer) for buffer in self.buffers], dtype=np.float32
        )

    def _compute_loadable_station_mask(self) -> np.ndarray:
        active = np.zeros(self.M, dtype=bool)
        for station in range(self.M):
            if self.station_jobs[station] is not None:
                continue
            if station == 0:
                active[station] = self.input_queue > 0
            else:
                active[station] = len(self.buffers[station - 1]) > 0
        return active

    def active_station_mask(self) -> np.ndarray:
        return self.current_decision_mask.copy()

    def action_mask(self) -> np.ndarray:
        """Boolean feasibility mask with shape [station, action]."""
        valid = np.zeros((self.M, 3), dtype=bool)
        valid[:, self.MAINTAIN] = True
        for station in range(self.M):
            if not self.current_decision_mask[station]:
                continue
            for action_index, delta in enumerate(self.ACTION_DELTAS):
                proposed = self._proposed_station_G(station, int(delta))
                valid[station, action_index] = bool(
                    self.stock_min[station] - 1e-9
                    <= proposed
                    <= self.stock_max[station] + 1e-9
                )
            valid[station, self.MAINTAIN] = True
        return valid

    # ------------------------------------------------------------------
    # Reset and primitive process progression
    # ------------------------------------------------------------------
    def reset(self, seed: Optional[int] = None):
        if seed is not None:
            self.rng = np.random.default_rng(seed)

        self.time = 0.0
        self.primitive_step_count = 0
        self.decision_count = 0
        self.G = self.stock_target * self.initial_stock_ratios
        self.T = self.base_cycle_time * self.initial_stock_ratios

        # Start with empty intermediate buffers. This removes an arbitrary
        # initial-WIP condition and prevents free reward from draining seeded jobs.
        self.buffers: List[List[Job]] = [[] for _ in range(self.M - 1)]
        self._update_buffer_levels()
        self._prev_buffer_total = float(np.sum(self.buffer_levels))

        self.station_jobs: List[Optional[Job]] = [None] * self.M
        self.remaining_time = np.zeros(self.M, dtype=np.float32)
        self.input_queue = 0
        self.lost_orders = 0
        self._prev_lost_orders = 0

        self.c = np.zeros(self.M, dtype=np.float32)
        self.DM = 0.0
        self.Y = 0.0
        self.last_action_applied_mask = np.zeros(self.M, dtype=np.int64)

        initial_regime = (
            int(self.fixed_regime)
            if self.fixed_regime is not None
            else (
                int(self.rng.integers(0, self.M))
                if self.random_initial_regime
                else self.NORMAL
            )
        )
        self.current_arrival_rate = self.base_arrival_rate
        self.next_arrival_time = 0.0
        self._set_regime(initial_regime, resample_arrival_clock=True)

        self.last_step_yield = 0.0
        self.last_step_type1 = 0.0
        self.last_step_type2 = 0.0
        self.last_step_arrivals = 0
        self.last_step_buffer_change = 0.0
        self.last_step_reward_vector = np.zeros(5, dtype=np.float32)
        self.last_step_reward = 0.0
        self.last_step_objective = 0.0
        self.last_elapsed_ticks = 0

        self.current_decision_mask = self._compute_loadable_station_mask()
        while not self.current_decision_mask.any() and self.time < self.horizon_time:
            self._advance_primitive_tick()
            self.current_decision_mask = self._compute_loadable_station_mask()

        return self._get_obs(), self._info()

    def _try_transfer_completed_job(self, station: int) -> Tuple[float, float, float]:
        job = self.station_jobs[station]
        if job is None or self.remaining_time[station] > 0.0:
            return 0.0, 0.0, 0.0

        step_yield = step_type1 = step_type2 = 0.0
        if not job.operation_completed:
            if self.rng.random() < job.assigned_type1_probability:
                self.c[station] += 1.0
                step_type1 += 1.0
                self.station_jobs[station] = None
                self.remaining_time[station] = 0.0
                return step_yield, step_type1, step_type2
            job.total_stock_removed += job.assigned_actual_removal
            job.finish_operation()

        if station == self.M - 1:
            if self._is_type2_defect(job.total_stock_removed):
                self.DM += 1.0
                step_type2 += 1.0
            else:
                self.Y += 1.0
                step_yield += 1.0
            self.station_jobs[station] = None
            self.remaining_time[station] = 0.0
        elif len(self.buffers[station]) < int(self.buffer_capacity[station]):
            job.clear_operation_snapshot()
            self.buffers[station].append(job)
            self.station_jobs[station] = None
            self.remaining_time[station] = 0.0
        # If the downstream buffer is full, the completed job remains blocked.
        return step_yield, step_type1, step_type2

    def _load_station(self, station: int, action_delta: int) -> None:
        if not self.current_decision_mask[station]:
            raise RuntimeError("Attempted to load an inactive station.")
        if station == 0:
            self.input_queue -= 1
            job = Job(arrival_time=self.time)
        else:
            job = self.buffers[station - 1].pop(0)

        proposed = self._proposed_station_G(station, action_delta)
        self.G[station] = np.float32(proposed)
        actual_removal = self._actual_removal_from_command(
            station, proposed
        )
        assigned_cycle = self._cycle_time_from_G(station, proposed)
        # T_i(t) reports the expected cycle-time setpoint under the current
        # regime. The realized noisy duration remains in remaining_time.
        self.T[station] = np.float32(
            self._expected_cycle_time_from_G(station, proposed)
        )
        assigned_p1 = self._type1_probability_from_G(station, proposed)
        job.prepare_operation(proposed, actual_removal, assigned_cycle, assigned_p1)
        self.station_jobs[station] = job
        self.remaining_time[station] = np.float32(assigned_cycle)

    def _primitive_reward(
        self,
        step_yield: float,
        step_type1: float,
        step_type2: float,
    ) -> Tuple[float, np.ndarray, Dict[str, float]]:
        self._update_buffer_levels()
        current_buffer_total = float(np.sum(self.buffer_levels))
        step_buffer_change = current_buffer_total - self._prev_buffer_total
        self._prev_buffer_total = current_buffer_total

        step_lost_orders = float(
            max(0, self.lost_orders - self._prev_lost_orders)
        )
        self._prev_lost_orders = int(self.lost_orders)

        reward_vector = np.array(
            [
                step_yield,
                step_type1,
                step_type2,
                step_buffer_change,
                step_lost_orders,
            ],
            dtype=np.float32,
        )
        reward_weights = np.array(
            [
                self.yield_reward,
                -self.type1_penalty,
                -self.type2_penalty,
                -self.buffer_change_penalty,
                -self.lost_order_penalty,
            ],
            dtype=np.float32,
        )
        reward = float(np.dot(reward_weights, reward_vector))
        diagnostics = {
            "step_yield": float(step_yield),
            "step_type1": float(step_type1),
            "step_type2": float(step_type2),
            "step_buffer_change": float(step_buffer_change),
            "step_lost_orders": float(step_lost_orders),
            "buffer_total": current_buffer_total,
        }
        return reward, reward_vector, diagnostics

    def _advance_primitive_tick(
        self,
    ) -> Tuple[float, np.ndarray, Dict[str, float], int]:
        self._advance_regime_clock()
        end_time = min(self.horizon_time, self.time + self.dt)
        elapsed = end_time - self.time
        arrivals = self._generate_arrivals_until(end_time)

        for station in range(self.M):
            job = self.station_jobs[station]
            if (
                job is not None
                and not job.operation_completed
                and self.remaining_time[station] > 0.0
            ):
                self.remaining_time[station] = max(
                    0.0, float(self.remaining_time[station] - elapsed)
                )

        step_yield = step_type1 = step_type2 = 0.0
        for station in reversed(range(self.M)):
            dy, d1, d2 = self._try_transfer_completed_job(station)
            step_yield += dy
            step_type1 += d1
            step_type2 += d2

        self.time = end_time
        self.primitive_step_count += 1
        reward, vector, diagnostics = self._primitive_reward(
            step_yield, step_type1, step_type2
        )
        return reward, vector, diagnostics, arrivals

    # ------------------------------------------------------------------
    # Event-triggered transition
    # ------------------------------------------------------------------
    def step(self, action: Sequence[int]):
        action_index = np.asarray(action, dtype=np.int64)
        if action_index.shape != (self.M,):
            raise ValueError(f"Expected action shape ({self.M},), got {action_index.shape}.")
        if np.any(action_index < 0) or np.any(action_index >= 3):
            raise ValueError("Each station action must be 0, 1, or 2.")
        if not self.current_decision_mask.any():
            raise RuntimeError("No active station at the current decision state.")

        current_regime = self.regime_id
        active_mask = self.current_decision_mask.copy()
        valid_mask = self.action_mask()
        executed = action_index.copy()
        invalid_count = 0

        for station in range(self.M):
            if not active_mask[station]:
                executed[station] = self.MAINTAIN
                continue
            if not valid_mask[station, action_index[station]]:
                executed[station] = self.MAINTAIN
                invalid_count += 1

        action_delta = self.ACTION_DELTAS[executed]

        for station in range(self.M):
            if active_mask[station]:
                self._load_station(station, int(action_delta[station]))
        self._update_buffer_levels()
        self.decision_count += 1
        self.last_action_applied_mask = active_mask.astype(np.int64)

        primitive_rewards: List[float] = []
        primitive_vectors: List[np.ndarray] = []
        interval_diag = {
            "step_yield": 0.0,
            "step_type1": 0.0,
            "step_type2": 0.0,
            "buffer_change": 0.0,
            "lost_orders": 0.0,
            "arrivals": 0,
        }

        while self.time < self.horizon_time - 1e-12:
            reward, vector, diag, arrivals = self._advance_primitive_tick()
            primitive_rewards.append(reward)
            primitive_vectors.append(vector)
            interval_diag["step_yield"] += diag["step_yield"]
            interval_diag["step_type1"] += diag["step_type1"]
            interval_diag["step_type2"] += diag["step_type2"]
            interval_diag["buffer_change"] += diag["step_buffer_change"]
            interval_diag["lost_orders"] += diag["step_lost_orders"]
            interval_diag["arrivals"] += int(arrivals)

            self.current_decision_mask = self._compute_loadable_station_mask()
            if self.current_decision_mask.any():
                break

        done = bool(self.time >= self.horizon_time - 1e-12)
        truncated = False
        if done:
            self.current_decision_mask = np.zeros(self.M, dtype=bool)

        elapsed_ticks = max(1, len(primitive_rewards))
        reward_total = float(np.sum(primitive_rewards))
        vector_total = (
            np.sum(np.stack(primitive_vectors), axis=0).astype(np.float32)
            if primitive_vectors
            else np.zeros(5, dtype=np.float32)
        )
        self.last_step_yield = float(interval_diag["step_yield"])
        self.last_step_type1 = float(interval_diag["step_type1"])
        self.last_step_type2 = float(interval_diag["step_type2"])
        self.last_step_arrivals = int(interval_diag["arrivals"])
        self.last_step_buffer_change = float(interval_diag["buffer_change"])
        self.last_step_reward_vector = vector_total.copy()
        self.last_step_reward = reward_total
        self.last_step_objective = reward_total
        self.last_elapsed_ticks = int(elapsed_ticks)

        observation = self._get_obs()
        info = self._info()
        info.update(
            {
                "regime_id_for_transition": int(current_regime),
                "regime_name_for_transition": self.REGIME_NAMES[current_regime],
                "selected_action_index": action_index.copy(),
                "executed_action_index": executed.copy(),
                "action_delta": action_delta.copy(),
                "action_applied_mask": active_mask.astype(np.int64),
                "next_active_station_mask": self.current_decision_mask.astype(np.int64),
                "invalid_action_count": int(invalid_count),
                "elapsed_ticks": int(elapsed_ticks),
                "primitive_rewards": np.asarray(primitive_rewards, dtype=np.float32),
                "primitive_reward_vectors": np.asarray(primitive_vectors, dtype=np.float32),
                "reward_components": {
                    "step_yield": float(interval_diag["step_yield"]),
                    "step_type1": float(interval_diag["step_type1"]),
                    "step_type2": float(interval_diag["step_type2"]),
                    "step_buffer_change": float(interval_diag["buffer_change"]),
                    "step_lost_orders": float(interval_diag["lost_orders"]),
                    "reward_vector": vector_total.copy(),
                    "objective_step": reward_total,
                },
            }
        )
        return observation, reward_total, done, truncated, info

    # ------------------------------------------------------------------
    # Document-aligned state and diagnostics
    # ------------------------------------------------------------------
    def _get_obs(self) -> np.ndarray:
        # G_i(t): commanded stock removal, normalized around the target profile.
        g_obs = np.tanh(np.log(np.maximum(self.G / self.stock_target, 1e-8)))
        # T_i(t): current deterministic cycle-time setpoint.
        t_obs = np.tanh(np.log(np.maximum(self.T / self.base_cycle_time, 1e-8)))
        # b_i(t): intermediate buffer occupancy.
        b_obs = np.clip(
            self.buffer_levels / np.maximum(self.buffer_capacity, 1), 0.0, 1.0
        )
        # c_i(t), D_M(t), and Y(t): bounded cumulative counts.
        count_scale = max(10.0, 0.30 * self.episode_horizon)
        c_obs = np.clip(self.c / count_scale, 0.0, 1.0)
        dm_obs = np.array([min(1.0, self.DM / count_scale)], dtype=np.float32)
        y_obs = np.array([min(1.0, self.Y / count_scale)], dtype=np.float32)
        # q(t): orders waiting before Station 1.
        q_obs = np.array(
            [min(1.0, self.input_queue / max(1, self.max_input_queue))],
            dtype=np.float32,
        )
        # tau_i(t): remaining processing time; o_i(t): occupancy indicators.
        tau_obs = np.clip(self.remaining_time / 30.0, 0.0, 1.0)
        o_obs = np.asarray(
            [1.0 if job is not None else 0.0 for job in self.station_jobs],
            dtype=np.float32,
        )
        # eta(t): time remaining until the next stochastic arrival.
        eta = max(0.0, self.next_arrival_time - self.time)
        eta_obs = np.array([np.tanh(eta / 10.0)], dtype=np.float32)

        observation = np.concatenate(
            [
                g_obs,
                t_obs,
                b_obs,
                c_obs,
                dm_obs,
                y_obs,
                q_obs,
                tau_obs,
                o_obs,
                eta_obs,
            ]
        ).astype(np.float32)
        if observation.shape != self.observation_space.shape:
            raise RuntimeError(
                f"Observation shape mismatch: {observation.shape} != {self.observation_space.shape}"
            )
        return observation

